"""Check every table in reports/step2_analysis.md against the generated artefacts.

The step-2 report is written by hand around numbers that are generated by
rank_b.py.  That is a place for a stale figure to survive an edit, and one did
survive one earlier in this project, so the check is a script rather than a
reading pass.

Three kinds of check:
  * generated blocks (section 3.1, section 7.5) must appear in the report byte
    for byte as report_tables.py renders them;
  * hand-written tables (2.2, 4) are parsed and every cell compared with
    step2_process_metrics.csv;
  * the robustness table (5) is compared with step2_metrics.json.

Run:  cd src && python3 verify_step2.py        (exit 0 = 0 mismatches)
"""
from __future__ import annotations

import os
import re
import sys

import report_tables as T
from common import REPORTS

REPORT = os.path.join(REPORTS, "step2_analysis.md")

bad: list[str] = []
checked = 0


def eq(where: str, field: str, got, want, tol: float = 0.0) -> None:
    global checked
    checked += 1
    ok = (abs(got - want) <= tol) if isinstance(want, float) else (got == want)
    if not ok:
        bad.append(f"{where}: {field} report={got} generated={want}")


def cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def num(s: str) -> float:
    return float(re.sub(r"[`*\s]", "", s))


def tol(cell: str) -> float:
    """Half a unit in the last place the report actually prints.

    The report quotes Client_ROI to 3 decimals and the CSV holds 4, so a cell
    reading 0.075 against a generated 0.0755 is a correct rounding, not a stale
    figure.  Anything outside half a displayed unit is a real mismatch.
    """
    txt = re.sub(r"[`*\s×x]", "", cell)
    dp = len(txt.split(".")[1]) if "." in txt else 0
    return 0.5 * 10 ** -dp + 1e-9


def main() -> int:
    text = open(REPORT, encoding="utf-8").read()
    rows = {r["label"]: r for r in T.rows()}
    js = T.metrics()

    # --- generated blocks ---------------------------------------------------
    for name in sorted(T.TABLES):
        global checked
        checked += 1
        if T.TABLES[name]() not in text:
            bad.append(f"generated block '{name}' is not in the report verbatim "
                       f"(re-paste `python3 report_tables.py {name}`)")

    lines = text.splitlines()

    # --- section 2.2: cases / sessions / minutes / median / p90 / CV --------
    for ln in lines:
        c = cells(ln)
        if len(c) != 7 or not c[0].startswith("`"):
            continue
        label = c[0].strip("`")
        r = rows.get(label)
        if not r:
            continue
        w = f"2.2 {label}"
        eq(w, "cases", int(c[1]), int(r["cases"]))
        eq(w, "sessions", int(c[2]), int(r["sessions"]))
        eq(w, "total_min", num(c[3]), round(float(r["total_s"]) / 60, 1), tol(c[3]))
        eq(w, "median_s", num(c[4]), float(r["median_s"]), tol(c[4]))
        eq(w, "p90_s", num(c[5]), float(r["p90_s"]), tol(c[5]))
        eq(w, "cv", num(c[6]), float(r["cv"]), tol(c[6]))

    # --- section 4: the ranking table ---------------------------------------
    seen = 0
    for ln in lines:
        c = cells(ln)
        if len(c) != 12 or not re.fullmatch(r"\**\d+\**", c[0]):
            continue
        label = c[1].strip("*` ").strip("`")
        r = rows.get(label)
        if not r:
            continue
        seen += 1
        w = f"4 {label}"
        eq(w, "rank", int(re.sub(r"\*", "", c[0])), int(r["rank"]))
        eq(w, "client_roi", num(c[2]), float(r["client_roi"]), tol(c[2]))
        eq(w, "impact", num(c[3]), float(r["impact"]), tol(c[3]))
        eq(w, "automatability", num(c[4]), float(r["automatability"]), tol(c[4]))
        eq(w, "client_feasibility", num(c[5]), float(r["client_feasibility"]), tol(c[5]))
        eq(w, "build_fit", num(c[6]), float(r["build_fit"]), tol(c[6]))
        eq(w, "cases", int(num(c[7])), int(r["cases"]))
        eq(w, "median_s", num(c[8]), float(r["median_s"]), tol(c[8]))
        eq(w, "variant_rate", num(c[9]), float(r["variant_rate"]), tol(c[9]))
        eq(w, "judgment_step", num(c[10]), float(r["judgment_step"]), tol(c[10]))
        eq(w, "sensitivity", num(c[11]), float(r["sensitivity"]), tol(c[11]))
    if seen != len(rows):
        bad.append(f"4: matched {seen} of {len(rows)} processes in the ranking table")

    # --- section 5: the robustness table ------------------------------------
    views = {
        "Base (as one process)": js["ranking"],
        "Conflated label split 50/50": js["robustness_conflated_split"],
        "Extension-less session removed": js["robustness_without_degraded_session"],
        "Thin worklist 種別 evidence dropped": js["robustness_without_thin_worklist_evidence"],
    }
    for ln in lines:
        c = cells(ln)
        if len(c) != 4:
            continue
        view = views.get(c[0])
        if view is None:
            continue
        top = sorted(view, key=lambda r: -r["client_roi"])[:2]
        for i, cell in enumerate(c[1:3]):
            m = re.match(r"`?([a-z_0-9]+)`?\s+([0-9.]+)", cell.strip("`* "))
            if not m:
                bad.append(f"5 {c[0]}: cannot parse cell {cell!r}")
                continue
            w = f"5 {c[0]} #{i + 1}"
            eq(w, "label", m.group(1), top[i]["label"])
            eq(w, "client_roi", float(m.group(2)), round(top[i]["client_roi"], 4), tol(m.group(2)))
        margin = top[0]["client_roi"] / top[1]["client_roi"]
        eq(f"5 {c[0]}", "margin", num(c[3].rstrip("×x")), round(margin, 1), tol(c[3]))

    # --- inline figures quoted in the prose of 3.1 and 7.5 ------------------
    # Section 5 carried a stale 0.183 for four days because prose and table
    # cells are exactly where a regenerated number fails to land.  Every figure
    # introduced by those two sections is rebuilt from the artefacts here and
    # required to appear verbatim.
    w = rows["fin_purchase_order_management"]
    clips = T.clip_total(w)
    portal = round(float(w["paste_source_in_portal"]) * clips)
    scratch = round(float(w["paste_source_scratch"]) * clips)
    f = js["failure_path_evidence"]
    total_clips = sum(T.clip_total(r) for r in rows.values())
    agreement = sum(float(r["paste_source_agreement"]) * T.clip_total(r)
                    for r in rows.values()) / total_clips
    inline = {
        "3.1 clips in segments": f"{total_clips} of B's\n872 clipboard events",
        "3.1 channel agreement": f"agree on {agreement * 100:.1f}%",
        "7.1 winner clip split": f"portal ({portal}) or from the note pad ({scratch})",
        "3.1 winner clip split": f"all {clips} of its copies come from the portal "
                                 f"({portal}) or the note pad ({scratch})",
        "7.5 uncommitted cases": f"{f['cases_with_no_observed_commit']} of the "
                                 f"{f['cases']}\ncases show no commit click",
        "7.5 happy path": f"Every one of the {f['cases']} observed cases is a happy path",
        "7.5 structured_target": f"`structured_target` {float(w['structured_target']):.2f}",
        "7.5 variant_rate": f"`variant_rate`\n{float(w['variant_rate']):.2f}",
        "7.5 mock_fidelity": f"`mock_fidelity` {float(w['mock_fidelity']):.2f}",
    }
    for where, claim in inline.items():
        checked += 1
        if claim not in text:
            bad.append(f"{where}: report does not carry {claim!r} as generated")

    print(f"verify_step2: {checked} checks, {len(bad)} mismatches")
    for b in bad:
        print("  MISMATCH", b)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
